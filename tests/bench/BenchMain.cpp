bool parseDouble(const char* text, double& out) noexcept {
    char* end = nullptr;
    errno = 0;
    const double value = std::strtod(text, &end);
    if (end == text || *end != '\0' || errno == ERANGE || !std::isfinite(value))
        return false;
    out = value;
    return true;
}

bool parseInt(const char* text, int& out) noexcept {
    char* end = nullptr;
    errno = 0;
    const long value = std::strtol(text, &end, 10);
    if (end == text || *end != '\0' || errno == ERANGE || value < std::numeric_limits<int>::min() ||
        value > std::numeric_limits<int>::max())
        return false;
    out = static_cast<int>(value);
    return true;
}

// Named --config resolution. Task P1.10 left this table empty and predicted that P2.1 would be the
// only place that ever needs to touch this function; that held exactly -- the two rows below are
// the whole of P2.1's edit to this file's CLI surface, and the parser, the validation and the error
// text above and below are untouched.
//
// A named config fixes ONLY the string count. Everything else about both configurations -- the full
// P1 monitoring chain, the shipped parameter defaults, 2x oversampling -- is what cnpg_bench
// already runs, so the rows do not restate it and cannot drift from it. The remaining flags stay
// live on top of a --config, which is what makes `--config p2_max8 --samplerate 96000` a question
// this tool can answer without a third named row.
struct NamedConfig {
    const char* name;
    int strings;
    const char* description;
};
constexpr NamedConfig kNamedConfigs[] = {
    {"p2_default6", 6, "the shipped default count: 6 strings through the full P1 monitoring chain"},
    {"p2_max8", 8, "the design maximum: 8 strings, same chain"},
};

bool resolveNamedConfig(const std::string& name, int& outStrings) noexcept {
    for (const NamedConfig& config : kNamedConfigs) {
        if (name == config.name) {
            outStrings = config.strings;
            return true;
        }
    }
    return false;
}

void printNamedConfigs(std::FILE* stream) {
    std::fprintf(stream, "named configurations:\n");
    for (const NamedConfig& config : kNamedConfigs)
        std::fprintf(stream, "  %-12s %d strings -- %s\n", config.name, config.strings, config.description);
}

bool parseArgs(int argc, char** argv, BenchArgs& args, bool& configGiven, bool& stringsGiven) {
    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];

        const auto nextValue = [&](const char* flagName) -> const char* {
            if (i + 1 >= argc) {
                std::fprintf(stderr, "cnpg_bench: missing value for %s\n", flagName);
                return nullptr;
            }
            return argv[++i];
        };

        if (arg == "--config") {
            const char* value = nextValue("--config");
            if (value == nullptr)
                return false;
            args.configName = value;
            configGiven = true;
        } else if (arg == "--strings") {
            const char* value = nextValue("--strings");
            if (value == nullptr || !parseInt(value, args.strings)) {
                std::fprintf(stderr, "cnpg_bench: invalid --strings value\n");
                return false;
            }
            stringsGiven = true;
        } else if (arg == "--samplerate") {
            const char* value = nextValue("--samplerate");
            if (value == nullptr || !parseDouble(value, args.sampleRate)) {
                std::fprintf(stderr, "cnpg_bench: invalid --samplerate value\n");
                return false;
            }
        } else if (arg == "--blocksize") {
            const char* value = nextValue("--blocksize");
            if (value == nullptr || !parseInt(value, args.blockSize)) {
                std::fprintf(stderr, "cnpg_bench: invalid --blocksize value\n");
                return false;
            }
        } else if (arg == "--oversample") {
            const char* value = nextValue("--oversample");
            if (value == nullptr || !parseInt(value, args.oversample)) {
                std::fprintf(stderr, "cnpg_bench: invalid --oversample value\n");
                return false;
            }
        } else if (arg == "--seconds") {
            const char* value = nextValue("--seconds");
            if (value == nullptr || !parseDouble(value, args.seconds)) {
                std::fprintf(stderr, "cnpg_bench: invalid --seconds value\n");
                return false;
            }
        } else if (arg == "--help" || arg == "-h") {
            printUsage(stdout);
            std::exit(0);
        } else {
            std::fprintf(stderr, "cnpg_bench: unknown argument '%s'\n", arg.c_str());
            return false;
        }
    }
    return true;
}

