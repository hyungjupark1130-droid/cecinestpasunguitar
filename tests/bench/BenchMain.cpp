// Nearest-rank percentile over an already-sorted (ascending) vector. Not linear-interpolated:
// docs/plan.md section 4.7 only ever asks for "median, p99, and max", and the P1.8 ledger note
// (single-run figures get ~2 significant figures on a shared workstation) makes interpolation
// precision here moot -- nearest-rank also matches the simpler median() helper
// tests/dsp/DenormalTests.cpp already established for this repo's block-timing reports.
double percentileOfSorted(const std::vector<double>& sorted, double p) noexcept {
    if (sorted.empty())
        return 0.0;
    const auto rank = static_cast<std::size_t>(p * static_cast<double>(sorted.size() - 1) + 0.5);
    return sorted[std::min(rank, sorted.size() - 1)];
}

