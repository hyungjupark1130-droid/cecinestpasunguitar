int main(int argc, char** argv) {
    BenchArgs args;
    bool configGiven = false;
    bool stringsGiven = false;

    if (!parseArgs(argc, argv, args, configGiven, stringsGiven)) {
        printUsage(stderr);
        return 1;
    }

    if (configGiven && stringsGiven) {
        std::fprintf(stderr, "cnpg_bench: specify either --config or --strings, not both\n");
        return 1;
    }

    if (configGiven) {
        int resolvedStrings = 0;
        if (!resolveNamedConfig(args.configName, resolvedStrings)) {
            std::fprintf(stderr, "cnpg_bench: unknown --config '%s'\n", args.configName.c_str());
            printNamedConfigs(stderr);
            return 1;
        }
        args.strings = resolvedStrings;
    }

    if (args.strings < 1 || args.strings > kMaxStrings) {
        std::fprintf(stderr, "cnpg_bench: --strings must be within 1..%d\n", kMaxStrings);
        return 1;
    }
    if (!(args.sampleRate > 0.0) || args.sampleRate > 500000.0) {
        std::fprintf(stderr, "cnpg_bench: --samplerate must be a positive, finite value\n");
        return 1;
    }
    if (args.blockSize < 1 || args.blockSize > 1000000) {
        std::fprintf(stderr, "cnpg_bench: --blocksize must be within 1..1000000\n");
        return 1;
    }
    if (args.oversample < 1 || args.oversample > kMaxOversampling) {
        std::fprintf(stderr, "cnpg_bench: --oversample must be within 1..%d (snapped to {2,4,8})\n", kMaxOversampling);
        return 1;
    }
    if (!(args.seconds > 0.0) || args.seconds > 100000.0) {
        std::fprintf(stderr, "cnpg_bench: --seconds must be a positive, finite value\n");
        return 1;
    }

    cnpg::test::P1Chain chain;
    chain.prepare(args.sampleRate, args.blockSize, args.strings, args.oversample);
    chain.reset();

    // Built once; re-applied to every module every block from inside the timed region (see the
    // file-level comment and cnpg::test::P1Chain::processBlock()).
    cnpg::test::P1ChainParams chainParams = cnpg::test::makeDefaultP1ChainParams();
    chainParams.numStrings = args.strings;

    NoteStreamGenerator generator(args.strings, args.sampleRate);

    const auto totalSamples = static_cast<long long>(args.seconds * args.sampleRate);
    constexpr double kWarmupSeconds = 1.0;
    const auto warmupSamplesRaw = static_cast<long long>(kWarmupSeconds * args.sampleRate);
    const long long warmupSamples = std::min(warmupSamplesRaw, totalSamples / 2);

    BlockEventQueue events;
    std::vector<double> blockMicros; // every measured block, in render order
    blockMicros.reserve(static_cast<std::size_t>(totalSamples / std::max(args.blockSize, 1) + 1));

    long long rendered = 0;
    long long nonFiniteSamples = 0;
    int warmupBlocks = 0;

    // FNV-1a over every rendered sample's raw bit pattern (untimed -- computed after `elapsed` is
    // captured, so it never pollutes a block-time measurement). This is the empirical determinism
    // check docs/plan.md section 4.7's "seeded/fixed... so runs are comparable" is asking for:
    // two runs with identical CLI arguments must print an identical audioHash, which is a much
    // stronger claim than "the note stream and the DSP chain contain no RNG or wall-clock read, so
    // it should be deterministic by construction" -- this is what actually checks that construction
    // held, on the real compiled binary, every time it runs.
    std::uint64_t audioHash = 14695981039346656037ull; // FNV-1a 64-bit offset basis
    constexpr std::uint64_t kFnvPrime = 1099511628211ull;

    while (rendered < totalSamples) {
        const auto numSamples = static_cast<int>(std::min<long long>(args.blockSize, totalSamples - rendered));

        events.clear();
        generator.fillBlock(rendered, numSamples, events);

        const auto start = std::chrono::steady_clock::now();
        {
            const ScopedFtzDazGuard ftzDazGuard; // exactly the guard the plugin's processBlock() engages
            chain.processBlock(chainParams, events, numSamples);
        }
        const auto elapsed = std::chrono::steady_clock::now() - start;
        const double micros =
            static_cast<double>(std::chrono::duration_cast<std::chrono::nanoseconds>(elapsed).count()) / 1000.0;

        blockMicros.push_back(micros);
        if (rendered < warmupSamples)
            ++warmupBlocks;

        for (int n = 0; n < numSamples; ++n) {
            const Sample sample = chain.mono[static_cast<std::size_t>(n)];
            nonFiniteSamples += std::isfinite(sample) ? 0 : 1;

            std::uint32_t bits = 0;
            std::memcpy(&bits, &sample, sizeof(bits));
            audioHash ^= bits;
            audioHash *= kFnvPrime;
        }

        rendered += numSamples;
    }

    // Clamp the warmup cut so at least one measured block always survives, even for a --seconds
    // value too short for a full kWarmupSeconds window (an edge case only a deliberately tiny
    // --seconds for smoke-testing the CLI would hit).
    const auto warmupCount = static_cast<std::size_t>(std::min(
        warmupBlocks, static_cast<int>(blockMicros.size()) - 1 < 0 ? 0 : static_cast<int>(blockMicros.size()) - 1));

    std::vector<double> stable(blockMicros.begin() + static_cast<std::vector<double>::difference_type>(warmupCount),
                               blockMicros.end());
    std::sort(stable.begin(), stable.end());

    const double medianMicros = percentileOfSorted(stable, 0.50);
    const double p99Micros = percentileOfSorted(stable, 0.99);
    const double maxMicros = stable.empty() ? 0.0 : stable.back();

    const double blockPeriodMicros = 1000000.0 * static_cast<double>(args.blockSize) / args.sampleRate;
    const auto toCpuPercent = [&](double micros) { return 100.0 * micros / blockPeriodMicros; };

    const int factor = chain.oversampler.factor();

    // Every lookup below runs once, here, outside the timed loop above.
    const std::string cpuModelStr = cpuModel();
    const unsigned int coreCount = logicalCoreCount();
    const std::string powerPlanGuid = windowsPowerPlanGuid();

    std::printf("cnpg_bench -- P1 monitoring chain, deterministic corpus-derived workload\n");
    std::printf("  strings=%d samplerate=%.0f blocksize=%d oversample=%d(requested %d) seconds=%.1f\n", args.strings,
                args.sampleRate, args.blockSize, factor, args.oversample, args.seconds);
    std::printf("  blocks total=%d measured=%d (warmup excluded=%d) nonFiniteSamples=%lld\n",
                static_cast<int>(blockMicros.size()), static_cast<int>(stable.size()), static_cast<int>(warmupCount),
                nonFiniteSamples);
    std::printf("  audioHash (FNV-1a/64 over every rendered sample; identical CLI args -> identical hash): "
                "%016llx\n",
                static_cast<unsigned long long>(audioHash));
    std::printf("  block period at this rate/blocksize: %.4f us (100%% of one core)\n", blockPeriodMicros);
    std::printf("  median block time: %10.3f us = %6.3f%% CPU\n", medianMicros, toCpuPercent(medianMicros));
    std::printf("  p99    block time: %10.3f us = %6.3f%% CPU\n", p99Micros, toCpuPercent(p99Micros));
    std::printf("  max    block time: %10.3f us = %6.3f%% CPU\n", maxMicros, toCpuPercent(maxMicros));
    std::printf("  environment: cpu=\"%s\" logicalCores=%u powerPlanGuid=%s compiler=\"%s\" buildType=%s "
                "gitCommit=%s\n",
                cpuModelStr.c_str(), coreCount, powerPlanGuid.c_str(), compilerName(), CNPG_BENCH_BUILD_TYPE,
                CNPG_BENCH_GIT_COMMIT);

    std::printf("{\"strings\":%d,\"sampleRate\":%.0f,\"blockSize\":%d,\"oversampleFactor\":%d,"
                "\"secondsRequested\":%.1f,\"blocksTotal\":%d,\"blocksMeasured\":%d,\"warmupBlocksExcluded\":%d,"
                "\"nonFiniteSamples\":%lld,\"audioHash\":\"%016llx\",\"medianBlockTimeUs\":%.3f,"
                "\"p99BlockTimeUs\":%.3f,\"maxBlockTimeUs\":%.3f,\"medianCpuPercent\":%.3f,\"p99CpuPercent\":%.3f,"
                "\"maxCpuPercent\":%.3f,\"cpuModel\":\"%s\",\"logicalCoreCount\":%u,\"powerPlanGuid\":\"%s\","
                "\"compiler\":\"%s\",\"buildType\":\"%s\",\"buildFlags\":\"%s\",\"gitCommit\":\"%s\"}\n",
                args.strings, args.sampleRate, args.blockSize, factor, args.seconds,
                static_cast<int>(blockMicros.size()), static_cast<int>(stable.size()), static_cast<int>(warmupCount),
                nonFiniteSamples, static_cast<unsigned long long>(audioHash), medianMicros, p99Micros, maxMicros,
                toCpuPercent(medianMicros), toCpuPercent(p99Micros), toCpuPercent(maxMicros), cpuModelStr.c_str(),
                coreCount, powerPlanGuid.c_str(), compilerName(), CNPG_BENCH_BUILD_TYPE, CNPG_BENCH_BUILD_FLAGS,
                CNPG_BENCH_GIT_COMMIT);

    return 0;
}
